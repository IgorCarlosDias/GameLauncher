-- ============================================================================
-- GameLauncher - Política de Segurança RLS exigindo Login (to authenticated)
-- Tabelas reais: public.games_playtime, public.game_sessions, public.launcher_meta, public.game_achievements
-- ============================================================================

-- 1. Garante que as 4 tabelas existem
create table if not exists public.games_playtime (
  id bigint generated by default as identity primary key,
  game_identifier text not null unique,
  name text not null,
  custom_name text,
  steam_id text,
  play_time integer not null default 0,
  play_count integer not null default 0,
  favorite boolean not null default false,
  last_played timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.game_sessions (
  id bigint generated by default as identity primary key,
  game_identifier text not null,
  game_name text not null,
  started_at timestamptz not null,
  ended_at timestamptz not null,
  duration integer not null default 0,
  unique (game_identifier, started_at)
);

create table if not exists public.launcher_meta (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.game_achievements (
  id bigint generated by default as identity primary key,
  game_identifier text not null,
  game_name text not null,
  steam_id text,
  api_name text not null,
  name text not null,
  description text,
  icon_url text,
  icon_gray_url text,
  hidden boolean not null default false,
  achieved boolean not null default false,
  unlock_time bigint not null default 0,
  updated_at timestamptz not null default now(),
  unique (game_identifier, api_name)
);

-- 2. Remove automaticamente qualquer política antiga (anon ou anterior) nessas 4 tabelas
do $$
declare
  pol record;
begin
  for pol in
    select policyname, tablename
    from pg_policies
    where schemaname = 'public'
      and tablename in ('games_playtime', 'game_sessions', 'launcher_meta', 'game_achievements')
  loop
    execute format('drop policy if exists %I on public.%I', pol.policyname, pol.tablename);
  end loop;
end $$;

-- 3. Ativa Row Level Security (RLS) nas 4 tabelas
alter table public.games_playtime enable row level security;
alter table public.game_sessions enable row level security;
alter table public.launcher_meta enable row level security;
alter table public.game_achievements enable row level security;

-- 4. Cria políticas exclusivas para usuários autenticados (to authenticated)
create policy "Allow authenticated all games_playtime"
  on public.games_playtime
  for all
  to authenticated
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

create policy "Allow authenticated all game_sessions"
  on public.game_sessions
  for all
  to authenticated
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

create policy "Allow authenticated all launcher_meta"
  on public.launcher_meta
  for all
  to authenticated
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

create policy "Allow authenticated all game_achievements"
  on public.game_achievements
  for all
  to authenticated
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

-- 5. Revoga acesso anônimo e garante acesso apenas para authenticated
revoke all on public.games_playtime from anon;
revoke all on public.game_sessions from anon;
revoke all on public.launcher_meta from anon;
revoke all on public.game_achievements from anon;

grant all on public.games_playtime to authenticated;
grant all on public.game_sessions to authenticated;
grant all on public.launcher_meta to authenticated;
grant all on public.game_achievements to authenticated;
